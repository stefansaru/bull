#!/usr/bin/env python3
"""
gen_references_index.py -- Regenerate wiki/entities/references/README.md from the reference pages.

Every page under entities/references/<kind>/ carries `type: reference` and a `ref_type`
(DR-014). This tool groups them by folder (kind), lists title / year / ref_type / status,
and counts pages still marked `needs-identification`. The auction catalogue table lives
in auctions/README.md (written by gen_census_wiki.py) and is linked, not repeated.

Read-only except for the index file. Usage: python gen_references_index.py wiki
"""
import os
import re
import sys

import yaml

KINDS = [
    ("books", "Books", "Monographs, histories, documentary collections, bibliographies."),
    ("catalogues", "Catalogues", "Catalogue *series* (numbering systems: Michel, Scott, Yvert, SG, LP) and the *editions* cited."),
    ("auctions", "Auction catalogues", "One page per sale, with its Bull's Head lots and postmarks. Full table: [[auctions/README|auction index]]."),
    ("articles", "Articles", "Journal articles, blog posts, web articles, unattributed notes."),
    ("web", "Web", "One page per site or online database, with `domains:` so `tools/link_report.py` can match inline URLs."),
    ("archives", "Archives & registers", "Archival fonds, museum and heritage registers."),
    ("compilations", "Compilations", "Pages this wiki compiles from several references (valuation tables, notable lots)."),
]


def frontmatter(path):
    text = open(path, encoding="utf-8").read()
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    try:
        return yaml.safe_load(text[3:end]) or {}
    except yaml.YAMLError:
        return {}


def title_of(fm, slug):
    t = fm.get("title")
    if isinstance(t, dict):
        t = t.get("en") or next(iter(t.values()), slug)
    return str(t or slug).replace("|", "\\|")


def main():
    vault = sys.argv[1]
    root = os.path.join(vault, "entities", "references")
    out = ["---", "id: entities/references/README", "type: reference", "ref_type: index",
           "title: {en: References}", "status: living", "---", "",
           "# References", "",
           "Everything the wiki cites, grouped by kind ([[../../meta/decisions/DR-014-reference-taxonomy|DR-014]]). "
           "Every factual claim links to one of these pages (DR-007). Images are not references: "
           "each image records the reference it comes from in `assets/rights.yml` (`source:`), and a "
           "reference can set `rights_default:` for all of its images.", "",
           "*Generated by `tools/gen_references_index.py`; do not edit by hand.*", ""]
    total = unidentified = 0
    summary = []
    sections = []
    for folder, heading, blurb in KINDS:
        d = os.path.join(root, folder)
        pages = sorted(f for f in os.listdir(d) if f.endswith(".md") and f != "README.md") if os.path.isdir(d) else []
        rows = []
        for f in pages:
            fm = frontmatter(os.path.join(d, f))
            slug = f[:-3]
            status = fm.get("status", "")
            unidentified += status == "needs-identification"
            rows.append(f"| [[{folder}/{slug}\\|{title_of(fm, slug)}]] | {fm.get('year', '') or ''} | "
                        f"{fm.get('ref_type', '')} | {status} |")
        total += len(rows)
        summary.append(f"| [{heading}](#{heading.lower().replace(' & ', '--').replace(' ', '-')}) | {len(rows)} |")
        sections += [f"## {heading}", "", blurb, ""]
        if folder == "auctions":
            sections += [f"{len(rows)} sales: see the [[auctions/README|auction index]].", ""]
            continue
        sections += ["| Reference | Year | ref_type | Status |", "|---|---|---|---|", *rows, ""]
    out += ["| Kind | Pages |", "|---|---|", *summary, f"| **Total** | **{total}** |", "",
            f"{unidentified} page(s) are `needs-identification`: their author, date or origin "
            "must be recorded before they can back a claim.", "", *sections]
    with open(os.path.join(root, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote entities/references/README.md ({total} references, {unidentified} need identification)")


if __name__ == "__main__":
    main()
